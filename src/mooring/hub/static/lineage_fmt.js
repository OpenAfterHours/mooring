"use strict";

// Pure, DOM-free wording for recorded lineage — the row badge, the Pull impact list, and
// the sentence a destructive confirm appends. Loaded BEFORE app.js (exposes `LineageFmt`
// as a bare global + on `window`, the files_tree.js idiom); under Node it is require()d by
// tests/js. Nothing here touches the DOM, network, or storage.
//
// One rule governs every function in this file: it may only ever say what IS recorded.
// The server (mooring/lineage.py `counts`) never sends a zero — `readers`/`writers` are
// present only when non-zero, and a path with neither gets no payload at all — so there is
// no zero here to phrase. That matters most on a DERIVED OUTPUT: a generated extract is
// precisely the file a dashboard or a colleague's spreadsheet is most likely to be reading
// without mooring ever hearing about it, so a badge on that row saying "0 notebooks read
// this" would be both authoritative-looking and probably false.
//
// The other rule: every claim is DATED. A receipt entry is only removed by `mi.reset()`,
// so a notebook that stopped reading a file goes on asserting it did until it next runs.
// `as_of`/`stale` come from the server; nothing here states a claim without its age.

const LineageFmt = (function () {
  const plural = (n, word) => `${n} ${word}${n === 1 ? "" : "s"}`;
  const verb = (n, word) => `${word}${n === 1 ? "s" : ""}`;

  // The positive claims a payload supports, as phrases. Never a phrase about a zero:
  // an absent count is silence, not a "nobody does" finding.
  function claims(lineage) {
    const lin = lineage || {};
    const out = [];
    if (lin.readers) out.push(`${plural(lin.readers, "notebook")} ${verb(lin.readers, "read")} it`);
    if (lin.writers) {
      out.push(`${plural(lin.writers, "notebook")} ${verb(lin.writers, "generate")} it`);
    }
    return out;
  }

  // How old the weakest claim is. The server sends the OLDEST contributing receipt, so a
  // count is dated by its stalest member rather than vouched for by its freshest.
  function recency(lineage) {
    const lin = lineage || {};
    if (!lin.as_of) return "never dated";
    const day = String(lin.as_of).slice(0, 10);
    return lin.stale ? `last recorded ${day}, not confirmed since` : `recorded ${day}`;
  }

  // {text, title} for the row badge, or null when there is nothing positive to show.
  function badge(lineage) {
    const lin = lineage || {};
    const bits = [];
    if (lin.readers) {
      bits.push(`${plural(lin.readers, "notebook")} ${verb(lin.readers, "read")} this`);
    }
    if (lin.writers) bits.push(`generated by ${lin.writers}`);
    if (!bits.length) return null;
    // The date rides in the badge TEXT only once the claim has gone stale — that is when
    // it stops being a current fact and starts being a historical one.
    const text = `⇄ ${bits.join(" · ")}${lin.stale ? ` (${recency(lin)})` : ""}`;
    const title =
      `Recorded lineage: ${claims(lin).join(", ")} — ${recency(lin)}. ` +
      "Built only from notebooks that record their inputs/outputs with mooring_inputs, so " +
      "it is a floor: there may be more readers it cannot see, and no badge is not " +
      "evidence a file is unused. `mooring lineage <path>` shows the whole recorded " +
      "chain. Value-free and local.";
    return { text, title };
  }

  // Row states where a pull actually REPLACES (or removes) the local file — the only ones
  // the impact confirm fires for. "new remote" has no local copy to overwrite, and pull
  // SKIPS a conflict, so warning about either would be a warning the user cannot act on.
  const OVERWRITE_STATES = new Set(["remote changed", "deleted remotely"]);

  // Rows a Pull would overwrite that something is recorded against — [{path, readers,
  // writers, state, as_of, stale}], busiest first. Writers count as well as readers: a
  // pull that lands the team's copy over an extract YOUR notebook regenerates is the same
  // surprise from the other direction, and the badge already flags that row.
  function pullImpact(files) {
    const hits = [];
    for (const f of files || []) {
      if (!OVERWRITE_STATES.has(f.state)) continue;
      const lin = f.lineage;
      if (!lin || (!lin.readers && !lin.writers)) continue;
      hits.push({
        path: f.path,
        readers: lin.readers || 0,
        writers: lin.writers || 0,
        state: f.state,
        as_of: lin.as_of || "",
        stale: !!lin.stale,
      });
    }
    return hits.sort(
      (a, b) => b.readers - a.readers || b.writers - a.writers || a.path.localeCompare(b.path)
    );
  }

  // One line per affected file in the Pull confirm.
  function impactLine(hit) {
    const acts = [];
    if (hit.readers) acts.push(`${plural(hit.readers, "notebook")} ${verb(hit.readers, "read")}`);
    if (hit.writers) {
      acts.push(`${plural(hit.writers, "notebook")} ${verb(hit.writers, "generate")}`);
    }
    const what = hit.state === "deleted remotely" ? "removes" : "replaces";
    return `  ${hit.path} — ${what} a file ${acts.join(" and ")} (${recency(hit)})`;
  }

  // The clause a destructive confirm (Delete, Discard changes, Restore) appends for a row
  // others depend on. "" when nothing is recorded — the dialog must read exactly as it did
  // before rather than gain a reassuring "nothing depends on this".
  function impactWarning(lineage) {
    const said = claims(lineage);
    if (!said.length) return "";
    return (
      `\n\nOther notebooks depend on this file: ${said.join(", ")} (${recency(lineage)}).` +
      "\nLineage only sees notebooks that record their inputs, so there may be more."
    );
  }

  return { claims, recency, badge, pullImpact, impactLine, impactWarning, OVERWRITE_STATES };
})();

if (typeof window !== "undefined") window.LineageFmt = LineageFmt;
if (typeof module !== "undefined" && module.exports) module.exports = LineageFmt;
